import { acceptanceUsername, acceptancePassword } from './acceptance-credentials.mjs';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const output = '../.qa-work/QA03/alert-existing';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173/login');
await page.getByPlaceholder('账号', { exact: true }).fill(acceptanceUsername);
await page.getByPlaceholder('密码（至少 8 位）').fill(acceptancePassword);
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL('**/home');
const relations = (await (await context.request.get('http://127.0.0.1:5173/api/relations')).json()).relations;
const patient = relations.find(item => item.display_id === '模拟患儿A');
const home = await (await context.request.get(`http://127.0.0.1:5173/api/patients/${patient.patient_id}/home`)).json();
assert.ok(home.current_alert_id);
const path = `/api/alerts/${home.current_alert_id}`;
const before = await (await context.request.get(`http://127.0.0.1:5173${path}`)).json();
assert.equal(before.validity, 'valid');
assert.equal(before.content_state, 'available');
await page.goto(`http://127.0.0.1:5173/alerts/${home.current_alert_id}`);
await page.getByText(before.content.approved_text, { exact: true }).waitFor();
await page.waitForLoadState('networkidle');
const geometry = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth, titles: [...document.querySelectorAll('h2')].map(element => element.textContent) }));
assert.ok(geometry.scroll <= geometry.width);
assert.ok(geometry.titles.indexOf('获准提示内容') < geometry.titles.indexOf('提示状态'));
await page.screenshot({ path: `${output}/S11-B.png`, fullPage: true });
const after = await (await context.request.get(`http://127.0.0.1:5173${path}`)).json();
assert.ok(after.read_at);
if (before.read_at) assert.equal(after.read_at, before.read_at);
await page.reload();
await page.getByText(before.content.approved_text, { exact: true }).waitFor();
await page.waitForLoadState('networkidle');
const repeated = await (await context.request.get(`http://127.0.0.1:5173${path}`)).json();
assert.equal(repeated.read_at, after.read_at);
assert.deepEqual(errors, []);
await writeFile(`${output}/results.json`, JSON.stringify({ testedAt: new Date().toISOString(), existingAlertOnly: true, action: 'confirm-existing-alert-read', checks: ['approved-content-before-metadata', 'read-time-idempotent', 'no-horizontal-overflow'], status: 'PASS', errors }, null, 2));
await browser.close();
console.log(JSON.stringify({ checks: 3, status: 'PASS' }));
