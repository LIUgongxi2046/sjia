async function saveDraft() {
  const button = page.getByRole('button', { name: '保存草稿', exact: true });
  await button.waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === '保存草稿' && !button.disabled));
  const saved = page.waitForResponse(response => /\/drafts(?:\/[^/]+)?$/.test(new URL(response.url()).pathname) && ['POST', 'PUT'].includes(response.request().method()));
  await button.click();
  const response = await saved;
  assert.ok(response.ok(), await response.text());
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].some(button => button.textContent === '正在保存草稿'));
  return await response.json();
}
async function submit(buttonName) {
  await page.waitForFunction(name => [...document.querySelectorAll('button')].some(button => button.textContent === name && !button.disabled), buttonName);
  const response = page.waitForResponse(value => /\/patients\/[^/]+\/records$/.test(new URL(value.url()).pathname) && value.request().method() === 'POST');
  await page.getByRole('button', { name: buttonName, exact: true }).click();
  const saved = await response;
  assert.equal(saved.status(), 201, await saved.text());
  const result = await saved.json();
  await page.waitForURL(`${baseURL}/records`);
  return result;
}

