async function api(path, data, expected = 200, method = data === undefined ? 'GET' : 'POST') {
  const response = await context.request.fetch(`${baseURL}${path}`, { method, data, headers: csrf ? { 'X-CSRFToken': csrf } : {} });
  const body = await response.json();
  assert.equal(response.status(), expected, `${method} ${path}: ${JSON.stringify(body)}`);
  assert.match(response.headers()['cache-control'], /no-store/);
  return body;
}
