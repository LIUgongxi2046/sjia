async function ready(count) {
  await page.waitForFunction(expected => {
    const section = document.querySelector('section[aria-label="本份资料照片"]');
    return section?.querySelectorAll('img').length === expected && !section.textContent.includes('正在处理照片');
  }, count, { timeout: 180000 });
}
async function ids() {
  return await page.getByRole('region', { name: '本份资料照片', exact: true }).locator('img').evaluateAll(images => images.map(image => image.getAttribute('src').split('/')[3]));
}
