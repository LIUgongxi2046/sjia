import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const baseURL = 'http://127.0.0.1:5174';
const root = new URL('../../.qa-work/QA04/', import.meta.url);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
const results = [];
page.on('dialog', dialog => dialog.accept());
await page.goto(`${baseURL}/login`);
await page.getByPlaceholder('账号', { exact: true }).fill('acceptance-family');
await page.locator('input[type=password]').fill('Local-accept-2026');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/register/observations`);
const encoded = await page.evaluate(async base64 => {
  const audio = new AudioContext();
  const decoded = await audio.decodeAudioData(Uint8Array.from(atob(base64), char => char.charCodeAt(0)).buffer);
  const destination = audio.createMediaStreamDestination();
  const source = audio.createBufferSource();
  source.buffer = decoded;
  source.connect(destination);
  const recorder = new MediaRecorder(destination.stream, { mimeType: 'audio/webm;codecs=opus' });
  const chunks = [];
  const completed = new Promise(resolve => { recorder.onstop = async () => resolve([...new Uint8Array(await new Blob(chunks).arrayBuffer())]); });
  recorder.ondataavailable = event => chunks.push(event.data);
  source.onended = () => recorder.stop();
  await audio.resume();
  recorder.start();
  source.start();
  const bytes = await completed;
  destination.stream.getTracks().forEach(track => track.stop());
  await audio.close();
  return bytes;
}, (await readFile(new URL('observation.wav', root))).toString('base64'));
const webm = Buffer.from(encoded);
await writeFile(new URL('browser-recording.webm', root), webm);
const recognized = page.waitForResponse(response => response.url().endsWith('/voice-transcription'), { timeout: 150000 });
await page.getByLabel('选择语音录音', { exact: true }).setInputFiles({ name: 'browser-recording.webm', mimeType: 'audio/webm;codecs=opus', buffer: webm });
assert.equal((await recognized).status(), 200);
await page.waitForFunction(() => document.querySelector('.voice-review textarea')?.value.length > 0);
const text = await page.getByLabel('语音转写与文字描述').inputValue();
assert.match(text, /38[.．]6|三十八[点點]六/);
assert.match(text, /没有|沒有/);
results.push({ id: 'real-MediaRecorder-WebM-local-ASR', status: 'PASS', text, bytes: webm.length, input: '授权测试音频经真实 Web Audio 与 MediaRecorder 编码，未调用设备麦克风' });

const started = page.waitForRequest(request => request.url().endsWith('/voice-transcription'));
await page.getByLabel('选择语音录音', { exact: true }).setInputFiles({ name: 'browser-recording.webm', mimeType: 'audio/webm', buffer: webm });
await started;
const cancelled = page.waitForEvent('requestfailed', request => request.url().endsWith('/voice-transcription'));
await page.getByRole('button', { name: '取消本次', exact: true }).click();
await cancelled;
assert.equal(await page.getByLabel('语音转写与文字描述').inputValue(), text);
assert.equal(await page.getByRole('button', { name: '继续说话', exact: true }).isEnabled(), true);
results.push({ id: 'cancel-real-transcription-preserves-prior-text', status: 'PASS' });
await writeFile(new URL('audio-browser.json', root), JSON.stringify({ testedAt: new Date().toISOString(), results }, null, 2));
await browser.close();
console.log(JSON.stringify(results));
