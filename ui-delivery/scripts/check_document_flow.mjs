const reportUrl=page.url();
await page.reload();
await page.locator('.original-thumb').waitFor();
const persisted=await page.evaluate(async()=>{
  const db=await new Promise((resolve,reject)=>{const request=indexedDB.open('sjia-original-documents');request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error);});
  const docs=await new Promise((resolve,reject)=>{const request=db.transaction('documents').objectStore('documents').getAll();request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error);});
  const result=await Promise.all(docs.map(async item=>({kind:item.kind,photos:item.photos.length,labs:item.labs,hash:[...new Uint8Array(await crypto.subtle.digest('SHA-256',await item.photos[0].file.arrayBuffer()))].map(byte=>byte.toString(16).padStart(2,'0')).join('')})));
  db.close();return result;
});
assert.equal(persisted.length,1);
assert.equal(persisted[0].hash,hashes[0]);
assert.deepEqual(persisted[0].labs,[]);
