def matches_expected(actual, expected):
    if isinstance(expected, dict):
        return isinstance(actual, dict) and all(key in actual and matches_expected(actual[key], value)
            for key, value in expected.items())
    if isinstance(expected, list):
        return isinstance(actual, list) and len(actual) == len(expected) and all(
            matches_expected(actual_value, expected_value)
            for actual_value, expected_value in zip(actual, expected))
    return actual == expected


def read_source(source):
    path = PROJECT_ROOT / source["path"]
    content = path.read_bytes()
    if source["format"] == "json":
        parsed = json.loads(content)
        if not isinstance(parsed, dict):
            raise ValueError(f"Expected JSON object: {source['path']}")
        for key, expected in source["required"].items():
            if key not in parsed or not matches_expected(parsed[key], expected):
                raise ValueError(f"Unexpected {key} in {source['path']}: {parsed.get(key)!r}")
    elif source["format"] == "text":
        text_content = content.decode("utf-8")
        for fragment in source["required"]["contains"]:
            if fragment not in text_content:
                raise ValueError(f"Missing required log fragment in {source['path']}: {fragment}")
    return {
        "task_id": source["task_id"],
        "path": source["path"],
        "sha256": hashlib.sha256(content).hexdigest(),
        "bytes": len(content),
        "claim": source["claim"],
        "scope": source["scope"],
    }


