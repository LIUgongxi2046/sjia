await phone.getByLabel('相册文件',{exact:true}).setInputFiles(files);
await page.locator('.original-tile').nth(1).waitFor();
console.log('已选择两张原始文件');
assert.equal(await page.locator('.original-tile').count(),2);
await phone.getByRole('button',{name:'打开原图第1张',exact:true}).click();
