import { chromium } from 'playwright';
const baseURL = 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${baseURL}/login`);
await page.fill('input[placeholder="账号"]', 'guardian-1');
await page.fill('input[type="password"]', 'demo-pass-1');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/account`);
await page.waitForSelector('.profile-card');
const accountStatus = await page.locator('.profile-card p').innerText();
const logoutCount = await page.getByRole('button', { name: '退出登录', exact: true }).count();
await page.goto(`${baseURL}/associations`);
await page.waitForSelector('.relation-list li, .empty-panel');
const childText = await page.locator('.relation-list li strong').first().innerText();
console.log(JSON.stringify({ accountStatus, logoutCount, childText, pageErrors: errors }));
await browser.close();
