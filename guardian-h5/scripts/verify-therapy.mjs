import { chromium } from 'playwright';
const baseURL = 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${baseURL}/login`);
await page.fill('input[placeholder="账号"]', 'guardian-1');
await page.fill('input[type="password"]', 'demo-pass-1');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/register/therapies`);
await page.fill('#therapy-name', '布洛芬');
await page.getByRole('button', { name: '确认并保存', exact: true }).click();
await page.waitForURL(`${baseURL}/records`);
await page.waitForSelector('.record-list li strong');
await page.waitForFunction(() => [...document.querySelectorAll('.record-list li strong')].some(el => el.textContent === '治疗资料'), null, { timeout: 10000 });
const kinds = await page.locator('.record-list li strong').allTextContents();
console.log(JSON.stringify({ kinds, pageErrors: errors }));
await browser.close();
