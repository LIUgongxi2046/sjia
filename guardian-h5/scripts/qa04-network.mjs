import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const baseURL = 'http://127.0.0.1:5174';
const root = new URL('../../.qa-work/QA04/', import.meta.url);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext();
const page = await context.newPage();
page.on('dialog', dialog => dialog.accept());
await page.goto(`${baseURL}/login`);
await page.getByPlaceholder('账号', { exact: true }).fill('acceptance-family');
await page.locator('input[type=password]').fill('Local-accept-2026');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/register/reports`);
const recognized = page.waitForResponse(response => response.url().endsWith('/report-ocr'), { timeout: 150000 });
await page.getByLabel('选择原始照片').setInputFiles({ name: 'report.png', mimeType: 'image/png', buffer: await readFile(new URL('report.png', root)) });
assert.equal((await recognized).status(), 200);
await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent === '重新识别本页').disabled);
const names = await page.getByLabel('原项目名称', { exact: true }).evaluateAll(inputs => inputs.map(input => input.value));
assert.equal(names.length, 4);
await context.setOffline(true);
await page.getByRole('button', { name: '重新识别本页', exact: true }).click();
await page.getByRole('alert').getByText('识别未完成：无法连接识别服务，请检查网络后重新尝试。原图与已有内容已经保留。', { exact: true }).waitFor();
assert.deepEqual(await page.getByLabel('原项目名称', { exact: true }).evaluateAll(inputs => inputs.map(input => input.value)), names);
assert.equal(await page.getByRole('region', { name: '照片 1', exact: true }).locator('img').isVisible(), true);
await context.setOffline(false);
const recovered = page.waitForResponse(response => response.url().endsWith('/report-ocr'), { timeout: 150000 });
await page.getByRole('button', { name: '重新识别本页', exact: true }).click();
assert.equal((await recovered).status(), 200);
await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent === '重新识别本页').disabled);
assert.equal(await page.getByLabel('原项目名称', { exact: true }).count(), 4);
await page.goto(`${baseURL}/register/observations`);
await page.getByRole('button', { name: '文字输入', exact: true }).click();
await page.getByLabel('语音转写与文字描述').fill('本次确认前保留的文字');
await context.setOffline(true);
await page.getByLabel('选择语音录音').setInputFiles({ name: 'voice.wav', mimeType: 'audio/wav', buffer: await readFile(new URL('observation.wav', root)) });
await page.getByRole('alert').getByText('无法连接语音转写服务，请检查网络后重新尝试。', { exact: true }).waitFor();
assert.equal(await page.getByLabel('语音转写与文字描述').inputValue(), '本次确认前保留的文字');
await context.setOffline(false);
const transcript = page.waitForResponse(response => response.url().endsWith('/voice-transcription'), { timeout: 150000 });
await page.getByRole('button', { name: '重新转写本次录音', exact: true }).click();
assert.equal((await transcript).status(), 200);
await page.waitForFunction(() => document.querySelector('.voice-review textarea').value.includes('38.6'));
assert.match(await page.getByLabel('语音转写与文字描述').inputValue(), /^本次确认前保留的文字\n/);
const results = [{ id: 'real-offline-OCR-preserve-recover-no-duplicates', status: 'PASS' }, { id: 'real-offline-audio-preserve-retry', status: 'PASS' }];
await writeFile(new URL('network.json', root), JSON.stringify({ testedAt: new Date().toISOString(), results }, null, 2));
await browser.close();
console.log(JSON.stringify(results));
