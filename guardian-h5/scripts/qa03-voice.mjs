import { acceptanceUsername, acceptancePassword } from './acceptance-credentials.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const baseURL = 'http://127.0.0.1:5174';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
page.setDefaultTimeout(10000);
const errors = [];
const results = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(`${baseURL}/login`);
await page.getByPlaceholder('账号', { exact: true }).fill(acceptanceUsername);
await page.locator('input[type=password]').fill(acceptancePassword);
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/register/observations`);
await page.getByRole('button', { name: '文字输入', exact: true }).click();
const source = '今天早上八点测量体温38.6摄氏度，没有皮疹，关节是否不舒服还不能确定。';
await page.getByLabel('语音转写与文字描述').fill(source);
await page.getByRole('button', { name: '提取候选并核对', exact: true }).waitFor();
const recognized = page.waitForResponse(response => response.url().endsWith('/recognition/voice-structure'), { timeout: 180000 });
await page.getByRole('button', { name: '提取候选并核对', exact: true }).click();
const response = await recognized;
assert.equal(response.status(), 200, await response.text());
const candidates = (await response.json()).candidates;
assert.equal(candidates.temperature, 38.6);
assert.equal(candidates.temperature_unit, 'C');
await page.getByRole('heading', { name: '核对语音候选', exact: true }).waitFor();
for (const width of [320, 390, 580]) {
  await page.setViewportSize({ width, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
}
await page.setViewportSize({ width: 320, height: 844 });
await page.addStyleTag({ content: 'html { font-size: 200% !important; }' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
results.push({ id: 'voice-candidate-three-widths-and-large-text', status: 'PASS' });
assert.equal(await page.locator('#obs-temp').inputValue(), '');
await page.getByLabel('采用体温与单位', { exact: true }).check();
await page.getByLabel('已逐项核对候选与原文', { exact: true }).check();
await page.getByRole('button', { name: '确认采用所选候选', exact: true }).click();
assert.equal(await page.locator('#obs-temp').inputValue(), '38.6');
assert.equal(await page.getByLabel('体温单位', { exact: true }).inputValue(), '摄氏度（°C）');
assert.ok((await page.locator('#obs-desc').inputValue()).includes(source));
const draftSaved = page.waitForResponse(value => /\/drafts(?:\/[^/]+)?$/.test(new URL(value.url()).pathname) && ['POST', 'PUT'].includes(value.request().method()));
await page.getByRole('button', { name: '保存草稿', exact: true }).click();
assert.equal((await draftSaved).ok(), true);
await page.reload();
await page.waitForFunction(() => document.querySelector('#obs-temp')?.value === '38.6');
assert.ok((await page.locator('#obs-desc').inputValue()).includes(source));
const created = page.waitForResponse(value => /\/patients\/[^/]+\/records$/.test(new URL(value.url()).pathname) && value.request().method() === 'POST');
await page.getByRole('button', { name: '保存本次记录', exact: true }).click();
const saved = await created;
assert.equal(saved.status(), 201, await saved.text());
const recordId = (await saved.json()).record_id;
await page.waitForURL(`${baseURL}/records`);
const record = await (await context.request.get(`${baseURL}/api/records/${recordId}`)).json();
assert.equal(record.capture_method, 'voice_confirmed');
assert.equal(record.fields.find(field => field.field_code === 'temp').raw_numeric, '38.6');
assert.ok(record.fields.find(field => field.field_code === 'observation_note').raw_text.includes(source));
results.push({ id: 'voice-real-provider-confirm-save-read', status: 'PASS', recordId, candidates });

await page.goto(`${baseURL}/register/observations`);
await page.getByRole('button', { name: '文字输入', exact: true }).click();
await page.getByLabel('语音转写与文字描述').fill('本次体温39摄氏度。');
const pending = page.waitForRequest(value => value.url().endsWith('/recognition/voice-structure'));
await page.getByRole('button', { name: '提取候选并核对', exact: true }).click();
await pending;
await page.getByRole('button', { name: '取消本次提取', exact: true }).click();
await page.getByRole('button', { name: '文字输入', exact: true }).waitFor();
assert.equal(await page.locator('#obs-temp').inputValue(), '');
assert.equal(await page.locator('#obs-desc').inputValue(), '');
results.push({ id: 'voice-cancel-preserves-form', status: 'PASS' });
await page.getByRole('button', { name: '文字输入', exact: true }).click();
await page.getByLabel('语音转写与文字描述').fill('现在体温39.2摄氏度。');
const switching = page.waitForRequest(value => value.url().endsWith('/recognition/voice-structure'));
await page.getByRole('button', { name: '提取候选并核对', exact: true }).click();
await switching;
const relations = (await (await context.request.get(`${baseURL}/api/relations`)).json()).relations;
const other = relations.find(item => item.display_id === '模拟患儿B');
page.on('dialog', dialog => dialog.accept());
await page.getByRole('link', { name: '返回', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.getByLabel('当前患儿').selectOption(other.patient_id);
await page.getByRole('link', { name: '记录症状', exact: true }).click();
await page.getByRole('button', { name: '文字输入', exact: true }).waitFor();
assert.equal(await page.locator('#obs-temp').inputValue(), '');
assert.equal(await page.locator('#obs-desc').inputValue(), '');
assert.equal(await page.getByRole('heading', { name: '核对语音候选', exact: true }).count(), 0);
results.push({ id: 'voice-patient-switch-clears-pending-candidates', status: 'PASS' });
assert.deepEqual(errors, []);
await writeFile('../.qa-work/QA03/voice-ui.json', JSON.stringify({ testedAt: new Date().toISOString(),
  database: 'sjia_qa03', provider: 'actual Ark', dataMode: 'authorized synthetic', results, errors }, null, 2));
await browser.close();
console.log(JSON.stringify({ checks: results.length, passed: results.length }));
