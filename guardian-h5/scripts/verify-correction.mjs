import { chromium } from 'playwright';
const baseURL = 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${baseURL}/login`);
await page.fill('input[placeholder="账号"]', 'guardian-1');
await page.fill('input[type="password"]', 'demo-pass-1');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/register/observations`);
await page.fill('#obs-temp', '38.9');
await page.getByRole('button', { name: '保存本次记录', exact: true }).click();
await page.waitForURL(`${baseURL}/records`);
await page.locator('.record-list li a').first().click();
await page.waitForFunction(() => document.body.textContent.includes('体温'), null, { timeout: 10000 });
await page.getByRole('link', { name: '更正这份记录', exact: true }).click();
await page.waitForURL(/\/correct$/);
await page.fill('#corr-temp', '38.0');
await page.fill('#corr-reason', '重新核对体温');
await page.getByRole('button', { name: '保存更正', exact: true }).click();
await page.waitForURL(/\/records\//);
await page.waitForFunction(() => document.body.textContent.includes('版本 2'), null, { timeout: 10000 });
const subtitle = await page.locator('h1').innerText();
const versionText = await page.locator('body').innerText();
console.log(JSON.stringify({ subtitle, hasV2: versionText.includes('版本 2'), pageErrors: errors }));
await browser.close();
