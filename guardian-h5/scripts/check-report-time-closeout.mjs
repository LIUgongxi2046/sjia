import './registration-test-loader.mjs';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
for(const key of ['window','document','navigator','HTMLElement','Event']) Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const {createElement:h,act}=await import('react');
const {createRoot}=await import('react-dom/client');
const {ReportTimeSuggestion}=await import('../src/components/ReportTimeSuggestion.tsx');
const {timePayload}=await import('../src/components/medicalTimeValue.ts');
const {validateApiValue}=await import('../src/api/schema.ts');
const {reportFieldValue}=await import('../src/features/registration/reportFieldValue.ts');
const candidate={raw_text:'SYNTHETIC 2026-02',precision:'month',local_year:2026,local_month:2,end_year:null,end_month:null,
  relative_text:null,local_date:null,local_datetime:null,timezone_name:null,utc_offset_minutes:null,instant:null,resolution_status:'local_only'};
const item={name:'synthetic',value:'1.2500',comparator:'=',unit:'synthetic-unit',reference:null,method:null,source_text:candidate.raw_text,sample_time:candidate};
validateApiValue('report-recognition.schema.json',{candidates:{schema_version:'report-recognition-3',source_text:candidate.raw_text,sample_time:candidate,result_time:null,items:[item]}});
validateApiValue('report-recognition.schema.json',{candidates:{items:[Object.fromEntries(Object.entries(item).filter(([key])=>key!=='sample_time'))]}});
let adopted=null;
const root=createRoot(document.getElementById('root'));
await act(async()=>root.render(h(ReportTimeSuggestion,{label:'项目 1 采样时间',candidate,onAdopt:value=>{adopted=value;}})));
assert.equal(adopted,null,'rendering must not adopt a candidate');
assert.match(document.body.textContent,/SYNTHETIC 2026-02/);
assert.equal(reportFieldValue({...item,timeCandidates:{item:candidate,reportSample:candidate,reportResult:null,sourceText:candidate.raw_text}}).medical_time,null,'candidate metadata must not enter formal field');
await act(async()=>document.querySelector('button').click());
assert.deepEqual(timePayload(adopted),candidate,'explicit adoption preserves raw month precision without synthetic day');
const offset={...candidate,raw_text:'SYNTHETIC 2026-02-03 12:34 +08:00',precision:'minute',local_year:null,local_month:null,local_datetime:'2026-02-03T12:34',utc_offset_minutes:480};
adopted=null;
await act(async()=>root.render(h(ReportTimeSuggestion,{label:'报告出具时间',candidate:offset,onAdopt:value=>{adopted=value;}})));
assert.equal(adopted,null);
await act(async()=>document.querySelector('button').click());
assert.deepEqual(timePayload(adopted),offset,'exact offset is preserved without invented zone');
await act(async()=>root.unmount());
console.log('PASS report-time v2/v3 response validation, no automatic adoption, raw precision and offset preservation');
