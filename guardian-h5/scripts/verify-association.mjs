import { chromium } from 'playwright';
const baseURL = 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`${baseURL}/login`);
await page.fill('input[placeholder="账号"]', 'guardian-1');
await page.fill('input[type="password"]', 'demo-pass-1');
await page.getByRole('button', { name: '登录', exact: true }).click();
await page.waitForURL(`${baseURL}/home`);
await page.goto(`${baseURL}/associations`);
await page.waitForSelector('.relation-list li a');
await page.locator('.relation-list li a').first().click();
await page.waitForFunction(() => document.body.textContent.includes('关联详情'), null, { timeout: 10000 });
await page.waitForFunction(() => document.body.textContent.includes('demo-child'), null, { timeout: 10000 });
const detail = await page.locator('.facts div').allTextContents();
await page.goto(`${baseURL}/associations/new`);
await page.fill('#apply-evidence', '本人为患儿监护人');
await page.getByRole('button', { name: '提交申请', exact: true }).click();
await page.waitForURL(`${baseURL}/associations`);
console.log(JSON.stringify({ detail: detail.slice(0, 4), applyReturned: true, pageErrors: errors }));
await browser.close();
